"""Rebuild assets.js from the files in .\\source and .\\images.

Run this after replacing any of those files (requires: pip install pypdf pymupdf pillow):

    python build_assets.py

assets.js embeds (base64):
  - artwork for the recreated Delivery Requirement Sheet (header/footer art, section tabs, icons, logo)
  - the Century Gothic fonts embedded in the original sheet
  - forms appended to the sheet when selected as requirements (CA FR2257CA consent, F6445 PAC form)
  - the DocuSign / PAC instruction PDFs and the MMSD logo used by the emails
"""
import base64
import io
import json
from pathlib import Path

import pymupdf
import pypdf
from pypdf.generic import IndirectObject
from PIL import Image

HERE = Path(__file__).resolve().parent
SRC = HERE / "source"
IMAGES = HERE / "images"
SHEET = SRC / "MMSD Delivery Requirement Sheet.pdf"

# Images inside the original sheet (PDF object numbers) reused by the recreated page.
SHEET_IMAGES = {
    "headerArt": 478,     # blue swoosh behind the header
    "footerArt": 502,     # footer swoosh
    "tabPill": 494,       # navy section title pill (with shadow)
    "circleBlue": 496,
    "circleOrange": 508,
    "circleNavy": 530,
    "iconPolicy": 498,
    "iconPremium": 518,
    "iconReturn": 490,
    "iconImportant": 510,
    "iconRequirements": 534,
    "iconEmail": 484,
    "iconCheck": 512,
}
NAVY = (0, 46, 107)


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def res(o):
    return o.get_object() if isinstance(o, IndirectObject) else o


def png(img: Image.Image, max_side=None) -> str:
    if max_side and max(img.size) > max_side:
        img = img.copy()
        img.thumbnail((max_side, max_side), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "PNG", optimize=True)
    return b64(buf.getvalue())


def sheet_images():
    doc = pymupdf.open(str(SHEET))
    out = {}
    for key, xref in SHEET_IMAGES.items():
        pix = pymupdf.Pixmap(doc, xref)
        smask = doc.extract_image(xref).get("smask")
        if smask:
            pix = pymupdf.Pixmap(pix, pymupdf.Pixmap(doc, smask))
        out[key] = b64(pix.tobytes("png"))
    return out


def recolor(path: Path, rgb) -> Image.Image:
    img = Image.open(path).convert("RGBA")
    solid = Image.new("RGBA", img.size, rgb + (255,))
    solid.putalpha(img.getchannel("A"))
    return solid


def form_font(key) -> bytes:
    reader = pypdf.PdfReader(str(SHEET))
    fonts = res(res(res(reader.trailer["/Root"]["/AcroForm"])["/DR"])["/Font"])
    descriptor = res(res(fonts[key])["/FontDescriptor"])
    return res(descriptor["/FontFile2"]).get_data()


def main():
    assets = {
        **sheet_images(),
        "logoMassMutual": png(Image.open(IMAGES / "logo.png")),
        "titleBand": png(Image.open(IMAGES / "requirement_header.png")),
        "iconMail": png(recolor(IMAGES / "MM_Icon_Envelope.png", (0, 0, 0)), 160),
        "fontRegular": b64(form_font("/CenturyGothic")),
        "fontBold": b64(form_font("/CenturyGothic,Bold")),
        "fontItalic": b64(form_font("/CenturyGothic,Italic")),
        "caPage": b64((SRC / "CA Voluntary Electronic Delivery Opt-in Consent.pdf").read_bytes()),
        "pacPages": b64((SRC / "PAC F6445 7.2026.pdf").read_bytes()),
        "docusignInstructions": b64((SRC / "DocuSign instructions 2026.pdf").read_bytes()),
        "pacInstructions": b64((SRC / "NEW PAC INSTRUCTIONS.pdf").read_bytes()),
        "logoPng": b64((SRC / "MMSD logo.png").read_bytes()),
    }
    js = "// Generated by build_assets.py - do not edit by hand.\nwindow.ASSETS = " + json.dumps(assets) + ";\n"
    (HERE / "assets.js").write_text(js, encoding="ascii")
    for k, v in assets.items():
        print(f"{k:22s} {len(v) * 3 // 4:>10,d} bytes")


if __name__ == "__main__":
    main()
